import type { Family, TarotCard } from "../types.ts"

function major(
  numeral: string,
  name: string,
  keywords: [string, string],
  reversedKeywords: [string, string],
  meaning: string,
  reversedMeaning: string,
  scene: string,
): TarotCard {
  const id = name
    .toLowerCase()
    .replace(/^the /, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
  return {
    id,
    name,
    family: "major",
    numeral,
    keywords: [...keywords],
    reversedKeywords: [...reversedKeywords],
    meaning,
    reversedMeaning,
    scene,
  }
}

function minor(
  family: Exclude<Family, "major">,
  numeral: string,
  name: string,
  keywords: [string, string],
  reversedKeywords: [string, string],
  meaning: string,
  reversedMeaning: string,
  scene: string,
): TarotCard {
  return {
    id: `${family}-${numeral.toLowerCase().replace(/[^a-z0-9]+/g, "")}`,
    name,
    family,
    numeral,
    keywords: [...keywords],
    reversedKeywords: [...reversedKeywords],
    meaning,
    reversedMeaning,
    scene,
  }
}

